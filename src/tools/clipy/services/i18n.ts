const STORAGE_KEY_LANG = 'olovetools_lang'; // Unificamos a la clave global de oLoveTools
const SUPPORTED_LANGS = Object.keys(FLAGS) as Language[];

export const useTranslation = () => {
  const getLangFromPath = (): Language => {
    if (typeof window === 'undefined') return 'en';
    const path = window.location.pathname;
    
    // Extraemos todos los segmentos y buscamos el primero que sea un idioma válido
    const segments = path.split('/').filter(Boolean);
    const potentialLang = segments[0] as Language;
    
    // Si el primer segmento es un idioma válido (ej: /es/ o /es/página-rara), lo fijamos
    if (SUPPORTED_LANGS.includes(potentialLang)) {
      return potentialLang;
    }
    
    // Si estamos en la raíz, intentamos recuperar el idioma del almacenamiento
    const stored = localStorage.getItem(STORAGE_KEY_LANG) as Language;
    if (stored && SUPPORTED_LANGS.includes(stored)) {
        return stored;
    }

    return 'en';
  };

  const [lang] = useState<Language>(getLangFromPath());

  useEffect(() => {
    if (typeof window === 'undefined') return;
    const currentLangFromUrl = getLangFromPath();
    const storedLang = localStorage.getItem(STORAGE_KEY_LANG) as Language;
    const path = window.location.pathname;

    // Guardamos la preferencia actual en localStorage para persistencia
    localStorage.setItem(STORAGE_KEY_LANG, currentLangFromUrl);

    // Si estamos en la raíz ("/") y hay un idioma guardado que no es Inglés, redirigimos
    if (path === '/' && storedLang && storedLang !== 'en' && SUPPORTED_LANGS.includes(storedLang)) {
        window.location.href = `/${storedLang}/`;
    }
  }, []);


  const setLang = (newLang: Language) => {
    if (newLang === lang) return;
    localStorage.setItem(STORAGE_KEY_LANG, newLang);
    // Forzamos el cambio de URL física para retener la app y el idoma
    const target = `/${newLang}/clipy${window.location.search || ''}`;
    window.location.href = target;
  };

  const t = (key: string): string => {
    return DICTIONARY[lang][key] || DICTIONARY['en'][key] || key;
  };

  return { lang, setLang, t };
};